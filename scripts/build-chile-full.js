import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import ts from 'typescript';

const ROOT = resolve(import.meta.dirname, '..');
const NAME_FIELDS = ['nameAr', 'nameEn', 'nameFr', 'nameEs', 'nameDe'];
const INTERFACE = 'export interface KitchenDish { id: string; nameAr: string; nameEn: string; nameFr: string; nameEs: string; nameDe: string; category: string; mealType: string; grams: number; kcal: number; protein: number; carbs: number; fat: number; cooking?: string; region?: string; diaspora_priority?: string[]; }';

function compareParts(left, right) {
  return left.localeCompare(right, undefined, { numeric: true });
}

async function loadRows(directory) {
  const folder = resolve(ROOT, 'scripts', directory);
  if (!existsSync(folder)) throw new Error(`Missing source directory ${folder}`);
  const parts = readdirSync(folder)
    .filter((file) => /^part\d+-\d+\.mjs$/.test(file))
    .sort(compareParts);
  if (!parts.length) throw new Error(`No part modules in ${folder}`);

  const rows = [];
  for (const part of parts) {
    const file = resolve(folder, part);
    const exported = (await import(pathToFileURL(file).href)).default;
    if (!Array.isArray(exported)) throw new Error(`Expected rows array in ${file}`);
    rows.push(...exported);
  }
  return rows;
}

const base = await loadRows('chile-base-data');
const expansion = await loadRows('chile-data');
const require = createRequire(import.meta.url);
require.extensions['.ts'] = (module, filename) => {
  const source = readFileSync(filename, 'utf8');
  const compiled = ts.transpileModule(source, {
    compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022, esModuleInterop: true },
  });
  module._compile(compiled.outputText, filename);
};
const { CHILEAN_FULL } = require(resolve(ROOT, 'src', 'data', 'chilean-full.ts'));
const supplemental = CHILEAN_FULL.map(({ ref, note, ...dish }) => dish);
if (base.length !== 75 || expansion.length !== 75 || supplemental.length !== 100) {
  throw new Error(`Chile expects 75 base + 75 expansion + 100 supplemental rows; got ${base.length} + ${expansion.length} + ${supplemental.length}`);
}

const rows = [...base, ...expansion, ...supplemental];
const ids = new Set();
const englishNames = new Set();
const regions = new Set(['pan_chilean', 'santiago', 'valparaiso', 'maule', 'bio_bio', 'coquimbo', 'araucania', 'los_lagos', 'atacama', 'magallanes', 'aysen', 'arica']);
for (const [index, row] of rows.entries()) {
  for (const field of NAME_FIELDS) {
    if (typeof row[field] !== 'string' || !row[field].trim()) {
      throw new Error(`Chile row ${index + 1} is missing ${field}`);
    }
  }
  if (typeof row.id !== 'string' || !row.id.trim()) {
    throw new Error(`Chile row ${index + 1} is missing id`);
  }
  if (ids.has(row.id)) throw new Error(`Duplicate Chile dish id ${row.id}`);
  ids.add(row.id);
  const englishName = row.nameEn.trim().toLowerCase();
  if (englishNames.has(englishName)) throw new Error(`Duplicate Chile English dish name ${row.nameEn}`);
  englishNames.add(englishName);
  if (!regions.has(row.region)) throw new Error(`Chile row ${index + 1} has unknown region ${row.region}`);
  if (![row.grams, row.kcal, row.protein, row.carbs, row.fat].every(Number.isFinite)) {
    throw new Error(`Chile row ${index + 1} has invalid serving or nutrition values`);
  }
  if (row.kcal !== Math.round(4 * row.protein + 4 * row.carbs + 9 * row.fat)) {
    throw new Error(`Chile row ${index + 1} has inconsistent macro calories`);
  }
}
if (rows.length !== 250) throw new Error(`Chile expects 250 merged rows; got ${rows.length}`);

const output = resolve(ROOT, 'src', 'data', 'chile-full.ts');
const source = [
  '/* AUTO-GENERATED by scripts/build-chile-full.js from chile-base-data + chile-data. Do not edit. */',
  '// Chile: 75 base + 75 expansion + 100 supplemental dishes, with 5-language coverage checked.',
  INTERFACE,
  `export const CHILE_FULL: KitchenDish[] = ${JSON.stringify(rows, null, 2)};`,
  '',
].join('\n');
writeFileSync(output, source, 'utf8');
console.log(`Chile: ${base.length} base + ${expansion.length} expansion + ${supplemental.length} supplemental = ${rows.length} dishes`);
