import { existsSync, readdirSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';

const ROOT = resolve(import.meta.dirname, '..');
const NAME_FIELDS = ['nameAr', 'nameEn', 'nameFr', 'nameEs', 'nameDe'];
const INTERFACE = 'export interface KitchenDish { id: string; nameAr: string; nameEn: string; nameFr: string; nameEs: string; nameDe: string; category: string; mealType: string; grams: number; kcal: number; protein: number; carbs: number; fat: number; cooking?: string; region?: string; diaspora_priority?: string[]; }';

function compareParts(left, right) {
  return left.localeCompare(right, undefined, { numeric: true });
}

async function loadRows(directory) {
  const folder = resolve(ROOT, 'scripts', directory);
  if (!existsSync(folder)) throw new Error(`Missing source directory ${folder}`);
  const parts = readdirSync(folder)
    .filter((file) => /^part\d+-\d+\.mjs$/.test(file))
    .sort(compareParts);
  if (!parts.length) throw new Error(`No part modules in ${folder}`);

  const rows = [];
  for (const part of parts) {
    const file = resolve(folder, part);
    const exported = (await import(pathToFileURL(file).href)).default;
    if (!Array.isArray(exported)) throw new Error(`Expected rows array in ${file}`);
    rows.push(...exported);
  }
  return rows;
}

const base = await loadRows('chile-base-data');
const expansion = await loadRows('chile-data');
if (base.length !== 75 || expansion.length !== 75) {
  throw new Error(`Chile expects 75 base + 75 expansion rows; got ${base.length} + ${expansion.length}`);
}

const rows = [...base, ...expansion];
const ids = new Set();
const englishNames = new Set();
for (const [index, row] of rows.entries()) {
  for (const field of NAME_FIELDS) {
    if (typeof row[field] !== 'string' || !row[field].trim()) {
      throw new Error(`Chile row ${index + 1} is missing ${field}`);
    }
  }
  if (typeof row.id !== 'string' || !row.id.trim()) {
    throw new Error(`Chile row ${index + 1} is missing id`);
  }
  if (ids.has(row.id)) throw new Error(`Duplicate Chile dish id ${row.id}`);
  ids.add(row.id);
  const englishName = row.nameEn.trim().toLowerCase();
  if (englishNames.has(englishName)) throw new Error(`Duplicate Chile English dish name ${row.nameEn}`);
  englishNames.add(englishName);
}
if (rows.length !== 150) throw new Error(`Chile expects 150 merged rows; got ${rows.length}`);

const output = resolve(ROOT, 'src', 'data', 'chile-full.ts');
const source = [
  '/* AUTO-GENERATED by scripts/build-chile-full.js from chile-base-data + chile-data. Do not edit. */',
  '// Chile: 75 base + 75 expansion dishes, with 5-language coverage checked.',
  INTERFACE,
  `export const CHILE_FULL: KitchenDish[] = ${JSON.stringify(rows, null, 2)};`,
  '',
].join('\n');
writeFileSync(output, source, 'utf8');
console.log(`Chile: ${base.length} base + ${expansion.length} expansion = ${rows.length} dishes`);
