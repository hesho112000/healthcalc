export const resolveUSDA = (name: string): string | null => {
  const n = name?.trim();
  if (!n) return null;
  if (USDA_BASE[n]) return n;
  const alias = USDA_ALIASES[n];
  if (alias) return USDA_BASE[alias] ? alias : null;
  const key = norm(n);
  let best: string | null = null;
  let bestLen = 0;
  for (const k of Object.keys(USDA_BASE)) {
    const nk = norm(k);
    if (nk.length > bestLen && (key.includes(nk) || nk.includes(key))) {
      if (key.includes(nk) && nk.length > bestLen) {
        best = k;
        bestLen = nk.length;
      }
    }
  }
  if (best) return best;
  for (const [re, k] of TOKEN_RULES) {
    if (re.test(key) && USDA_BASE[k]) return k;
  }
  return null;
};

export interface VerificationResult {
  calories: number;
  protein: number;
  carbs: number;
  fat: number;
  fiber: number;
  sodium: number;
  sugar: number;
  saturatedFat: number;
  cholesterol: number;
  verified: boolean;
  source: string;
  baseKey: string | null;
}

export const getMealNutrition = (mealId: string, grams: number): VerificationResult => {
  const key = resolveUSDA(mealId);
  const empty: VerificationResult = {
    calories: 0, protein: 0, carbs: 0, fat: 0, fiber: 0, sodium: 0, sugar: 0,
    saturatedFat: 0, cholesterol: 0, verified: false,
    source: 'Authored estimate (not USDA verified)',
    baseKey: null,
  };
  if (!key) return empty;
  const base = USDA_BASE[key];
  const factor = grams / (base.perServing ?? 100);
  const round = (v: number | undefined): number => Math.round((v ?? 0) * factor);
  const round1 = (v: number | undefined): number => Math.round((v ?? 0) * factor * 10) / 10;
  return {
    calories: round(base.kcal),
    protein: round1(base.protein),
    carbs: round1(base.carbs),
    fat: round1(base.fat),
    fiber: round(base.fiber),
    sodium: round(base.sodium),
    sugar: round(base.sugar),
    saturatedFat: round(base.saturatedFat),
    cholesterol: round(base.cholesterol),
    verified: true,
    source: 'USDA FoodData Central 2024',
    baseKey: key,
  };
};

export interface EnrichableNutrition {
  name?: string;
  name_en?: string;
  calories?: number;
  protein?: number;
  carbs?: number;
  fat?: number;
  grams?: number;
}

export const usdaEnrich = <F extends EnrichableNutrition>(food: F, grams?: number): F & VerificationResult => {
  const name = (food.name_en ?? food.name ?? '').trim();
  const key = resolveUSDA(name);
  if (!key) {
    return {
      ...food,
      verified: false,
      source: 'Authored estimate (not USDA verified)',
      baseKey: null,
      fiber: 0, sodium: 0, sugar: 0, saturatedFat: 0, cholesterol: 0,
    } as F & VerificationResult;
  }
  const n = getMealNutrition(key, grams ?? (food as { portion?: { grams?: number; ml?: number } }).portion?.grams ?? (food as { portion?: { grams?: number; ml?: number } }).portion?.ml ?? 100);
  return {
    ...food,
    calories: n.calories,
    protein: n.protein,
    carbs: n.carbs,
    fat: n.fat,
    fiber: n.fiber,
    sodium: n.sodium,
    sugar: n.sugar,
    saturatedFat: n.saturatedFat,
    cholesterol: n.cholesterol,
    verified: true,
    source: n.source,
    baseKey: key,
  } as F & VerificationResult;
};